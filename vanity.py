#!/usr/bin/env python3
"""hiddenforge vanity - generate a Tor v3 vanity .onion address headlessly.

Runs INSIDE the hiddenforge image, where the vendored `mkp224o` binary lives.
The host CLI (`scripts/hiddenforge vanity`) invokes this via `docker run`; it can
also be run directly in the container:

    vanity.py --prefix myprefix --name myapp --out /var/lib/tor/hidden_service

It produces a directory that Tor accepts verbatim as a HiddenServiceDir:

    <out>/<name>/hostname              one line: <56-char base32>.onion
    <out>/<name>/hs_ed25519_public_key  64 B: 32 B tag + 32 B Ed25519 pubkey
    <out>/<name>/hs_ed25519_secret_key  96 B: 32 B tag + 64 B Ed25519 secret

Security properties:
  * The secret key's *contents* are never read, printed, or copied by this
    module. It is generated by mkp224o directly into the output directory; we
    only stat/rename/chmod it.
  * The address is independently re-derived from the generated public key, so a
    swapped or corrupt key set is detected before it is installed.
  * Refuses to touch an existing key set without --force. With --force the old
    set is *archived* (renamed aside), never deleted.
  * Directory 0700, files 0600 (hostname 0644 - it is the public address, and
    the entrypoint republishes it as <keys>/<name>.onion anyway).

Exit codes (shared with the host CLI):
    0  success
    1  generator failed / produced an unusable key set
    2  usage, validation, or already-exists without --force
    3  a key appeared at the destination while the search was running
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

# Tor v3: address = base32(pubkey || checksum || version). lower().rstrip("=") + ".onion"
# checksum = SHA3-256(".onion checksum" || pubkey || version)[:2], version = 0x03
ONION_CHECKSUM_PERSONAL = b".onion checksum"
ONION_VERSION = b"\x03"

SECRET_FILE = "hs_ed25519_secret_key"
PUBLIC_FILE = "hs_ed25519_public_key"
HOSTNAME_FILE = "hostname"

# Tor's on-disk tags. Each is 29 visible bytes plus three NULs == 32 bytes.
PUBLIC_TAG = b"== ed25519v1-public: type0 =="
SECRET_TAG = b"== ed25519v1-secret: type0 =="
TAG_LEN = 32
PUBKEY_LEN = 32
SECRET_LEN = 64


class KeyRaceError(FileExistsError):
    """A key set appeared at the destination while the search was running.

    Distinct from the ordinary "it already exists, pass --force" refusal, and it
    has its own exit code (3) in the contract this module and the host CLI share:
    2 means the operator asked for something impossible, 3 means something else
    wrote to the key volume underneath us and nothing was clobbered. Telling an
    automated caller that a race was a usage error sends it to the wrong remedy.

    It subclasses FileExistsError so any caller that only knows the old shape
    still catches it.
    """


B32_ALPHABET = set("abcdefghijklmnopqrstuvwxyz234567")  # RFC 4648 base32, lower
ONION_RE = re.compile(r"^[a-z2-7]{56}\.onion$")
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9\-]{0,62}$")
# A vanity prefix is a base32 label prefix; 1..7 is the useful range. 8+ is
# included so we can refuse it with an honest time estimate rather than a crash.
PREFIX_RE = re.compile(r"^[a-z2-7]{1,12}$")
DIFFICULTY_MAX_LEN = 8


def derive_onion(pubkey: bytes) -> str:
    """Return the v3 .onion address for a 32-byte Ed25519 public key."""
    if len(pubkey) != PUBKEY_LEN:
        raise ValueError(f"public key must be {PUBKEY_LEN} bytes, got {len(pubkey)}")
    checksum = hashlib.sha3_256(
        ONION_CHECKSUM_PERSONAL + pubkey + ONION_VERSION
    ).digest()[:2]
    return base64.b32encode(pubkey + checksum + ONION_VERSION).decode("ascii").lower() + ".onion"


def read_public_key(path: Path) -> bytes:
    """Extract the 32-byte pubkey from Tor's hs_ed25519_public_key file.

    Accepts both the tagged 64-byte form Tor (and mkp224o) write and a bare
    32-byte key, so a hand-assembled key volume still verifies.
    """
    data = path.read_bytes()
    if len(data) == TAG_LEN + PUBKEY_LEN and data.startswith(PUBLIC_TAG[: len(PUBLIC_TAG)]):
        return data[TAG_LEN:]
    if len(data) == PUBKEY_LEN:
        return data
    raise ValueError(
        f"{path.name}: expected {TAG_LEN + PUBKEY_LEN} bytes (tagged) or "
        f"{PUBKEY_LEN} bytes (bare), got {len(data)}"
    )


def read_hostname(path: Path) -> str | None:
    """Read and validate a Tor hostname file. Returns None if absent/unusable."""
    try:
        text = path.read_text(encoding="ascii").strip()
    except (OSError, UnicodeDecodeError):
        return None
    return text if ONION_RE.fullmatch(text) else None


# ---------------------------------------------------------------------------
# mkp224o
# ---------------------------------------------------------------------------

def mkp224o_path() -> str:
    for candidate in (
        os.environ.get("MKP224O"),
        "/usr/local/bin/mkp224o",
        "/usr/bin/mkp224o",
    ):
        if candidate and os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return candidate
    found = shutil.which("mkp224o")
    if not found:
        raise FileNotFoundError(
            "mkp224o not found. This subcommand requires the hiddenforge image "
            "(which vendors it); run it via `hiddenforge vanity` on the host."
        )
    return found


def _run_mkp224o(prefix: str, outbase: Path, threads: int, count: int = 1,
                 stats_every: int | None = None) -> subprocess.Popen:
    """Start mkp224o generating `count` key(s) matching `prefix` into outbase."""
    cmd = [mkp224o_path(), "-d", str(outbase), "-t", str(threads), "-n", str(count)]
    if stats_every is not None:
        cmd += ["-S", str(stats_every), "-T"]
    cmd.append(prefix)
    return subprocess.Popen(
        cmd, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True
    )


def _rate_from_stats_line(line: str) -> float | None:
    """Parse mkp224o's `>calc/sec:..., succ/sec:..., rest/sec:..., elapsed:...`.

    We want candidate keys *calculated* per second (`calc/sec`). `succ/sec` is
    zero during a benchmark because the benchmark filter is deliberately not
    findable, so it would always read 0.
    """
    m = re.search(r"calc/sec:\s*([0-9.]+)", line)
    if not m:
        return None
    try:
        return float(m.group(1))
    except ValueError:
        return None


def benchmark(seconds: int, threads: int) -> float:
    """Measure mkp224o key-generation throughput in keys/sec on this machine."""
    seconds = max(1, seconds)
    with tempfile.TemporaryDirectory(prefix="hf-bench-") as tmp:
        # A 10-character filter is never found in a benchmark window, so the
        # process only ever measures raw generation rate.
        proc = _run_mkp224o("zzzzzzzzzz", Path(tmp), threads, count=0, stats_every=1)
        best = 0.0
        deadline = time.monotonic() + seconds
        if proc.stderr is None:  # pragma: no cover - we always pass stderr=PIPE
            raise RuntimeError("mkp224o stderr pipe is unavailable")
        try:
            while time.monotonic() < deadline:
                line = proc.stderr.readline()
                if not line:
                    break
                rate = _rate_from_stats_line(line)
                if rate is not None:
                    best = rate  # keep the latest full-second sample
        finally:
            proc.terminate()
            try:
                proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                proc.kill()
        if best <= 0:
            raise RuntimeError("mkp224o produced no statistics; cannot benchmark")
        return best


def difficulty_table(rate: float, max_len: int = DIFFICULTY_MAX_LEN) -> list[dict]:
    """Honest expected-work table for prefixes of increasing length.

    Each base32 character multiplies the search space by 32, so expected
    attempts == 32**length and expected seconds == attempts / measured rate.
    """
    rows: list[dict] = []
    for length in range(1, max_len + 1):
        attempts = 32 ** length
        secs = attempts / rate if rate > 0 else float("inf")
        rows.append({
            "prefix_len": length,
            "average_attempts": attempts,
            "estimated_seconds": secs,
            "estimated_human": human_duration(secs),
        })
    return rows


def human_duration(seconds: float) -> str:
    if seconds < 1:
        return "<1s"
    if seconds < 60:
        return f"{seconds:.0f}s"
    if seconds < 3600:
        return f"{seconds / 60:.1f}m"
    if seconds < 86400:
        return f"{seconds / 3600:.1f}h"
    if seconds < 86400 * 365:
        return f"{seconds / 86400:.1f}d"
    return f"{seconds / (86400 * 365):.1f}y"


# ---------------------------------------------------------------------------
# Generation
# ---------------------------------------------------------------------------

def generate(prefix: str, name: str, out: Path, threads: int, force: bool,
             uid: int | None = None, gid: int | None = None) -> dict:
    target = out / name
    if (target.exists() or target.is_symlink()) and not force:
        raise FileExistsError(
            f"{target} already exists. Refusing to overwrite a key set: the key "
            f"IS the .onion address and there is no recovery. Pass --force to "
            f"archive the old one and generate a fresh address."
        )

    out.mkdir(parents=True, exist_ok=True, mode=0o700)
    with tempfile.TemporaryDirectory(prefix="hf-vanity-", dir=str(out)) as tmp:
        tmpdir = Path(tmp)
        proc = _run_mkp224o(prefix, tmpdir, threads, count=1)
        _, stderr = proc.communicate()
        if proc.returncode not in (0, None) and not list(tmpdir.glob("*.onion")):
            raise RuntimeError(
                f"mkp224o exited {proc.returncode}: {(stderr or '').strip()[-500:]}"
            )

        generated = [d for d in tmpdir.iterdir() if d.is_dir() and d.name.endswith(".onion")]
        if len(generated) != 1:
            raise RuntimeError(
                f"expected exactly one generated .onion directory, found {len(generated)}"
            )
        src = generated[0]

        # Verify before installing: the directory name, the hostname file, and
        # an independent derivation from the public key must all agree, and the
        # address must actually start with the requested prefix.
        dir_onion = src.name
        if not ONION_RE.fullmatch(dir_onion):
            raise RuntimeError(f"generator produced an invalid address name: {dir_onion!r}")
        if not dir_onion.startswith(prefix):
            raise RuntimeError(
                f"generated address {dir_onion} does not start with prefix {prefix!r}"
            )
        file_onion = read_hostname(src / HOSTNAME_FILE)
        if file_onion != dir_onion:
            raise RuntimeError(
                f"hostname file ({file_onion!r}) disagrees with directory name ({dir_onion!r})"
            )
        derived = derive_onion(read_public_key(src / PUBLIC_FILE))
        if derived != dir_onion:
            raise RuntimeError(
                f"address derived from public key ({derived}) disagrees with the "
                f"generated address ({dir_onion})"
            )

        # Archive, never delete, an existing key set.
        archived = None
        if (target.exists() or target.is_symlink()) and force:
            archived = _unique_archive_path(out, name)
            os.rename(target, archived)
            # The container's published copy of the address now names the key
            # just archived, and `hiddenforge show` reads it from the host (where
            # `hostname` is usually unreadable) until the container republishes.
            # Remove it: absent means "not ready", stale means "wrong address".
            (out / f"{name}.onion").unlink(missing_ok=True)

        try:
            os.rename(src, target)
        except OSError as exc:
            # Destination appeared between the pre-check and the rename.
            if target.exists():
                raise KeyRaceError(
                    f"{target} appeared while the search was running; refusing to "
                    f"clobber it (exit 3)"
                ) from exc
            raise

    _harden(target, uid, gid)
    return {
        "name": name,
        "onion": dir_onion,
        "key_path": str(target / SECRET_FILE),
        "public_key_path": str(target / PUBLIC_FILE),
        "address_path": str(target / HOSTNAME_FILE),
        "key_dir": str(target),
        "archived": str(archived) if archived else None,
        "threads": threads,
    }


def _unique_archive_path(out: Path, name: str) -> Path:
    base = out / f"{name}.replaced-{int(time.time())}"
    candidate, n = base, 1
    while candidate.exists():
        candidate = Path(f"{base}-{n}")
        n += 1
    return candidate


def _harden(keydir: Path, uid: int | None, gid: int | None) -> None:
    """0700 dir, 0600 secret/public, 0644 hostname; chown if requested.

    Every mode and owner is set on a DESCRIPTOR opened with ``O_NOFOLLOW``, never
    on a path. The previous version tested ``p.is_symlink()`` and then called
    ``os.chmod(p, ...)``, which re-resolves the name: between the two, a process
    able to write into the operator-supplied output directory could replace a
    regular file with a symlink and have this chmod land on its target. Linux has
    no ``lchmod``, so holding the descriptor is the only way to close that, and it
    is the same pattern entrypoint.py already uses for the key directories and the
    torrc. ``os.chown`` does support ``follow_symlinks=False``, but doing it on
    the descriptor keeps the mode and the owner referring to one inode.

    A symlink is still refused rather than followed: the open fails with ELOOP and
    the entry is left exactly as it was found. Tor has no use for a symlink inside
    a HiddenServiceDir, so nothing legitimate is lost.
    """
    u = uid if uid is not None else -1
    g = gid if gid is not None else -1
    chown = uid is not None or gid is not None

    dir_fd = os.open(keydir, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        for name in sorted(os.listdir(dir_fd)):
            try:
                fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=dir_fd)
            except OSError:
                # ELOOP: a symlink. Leave it alone entirely -- chowning it would
                # still be safe, but a symlink here means the directory is not
                # what we just wrote, and quietly tidying it would hide that.
                continue
            try:
                os.fchmod(fd, 0o644 if name == HOSTNAME_FILE else 0o600)
                if chown:
                    os.fchown(fd, u, g)
            finally:
                os.close(fd)
        # The directory last: 0700 closes it to everyone else, and doing it after
        # the entries means we could still open them by name.
        os.fchmod(dir_fd, 0o700)
        if chown:
            os.fchown(dir_fd, u, g)
    finally:
        os.close(dir_fd)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def _emit(rc: int, as_json: bool, payload: dict, human: str) -> int:
    if as_json:
        doc = {"ok": rc == 0, "exit_code": rc}
        doc.update({k: v for k, v in payload.items() if v is not None})
        print(json.dumps(doc, sort_keys=True))
    else:
        if human:
            print(human)
    return rc


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(
        prog="vanity.py",
        description="Generate a Tor v3 vanity address inside the hiddenforge image.",
    )
    ap.add_argument("--prefix", required=True,
                    help="base32 prefix to search for (1-7 chars is useful)")
    ap.add_argument("--name", default="myapp",
                    help="service directory name under --out (default: myapp)")
    ap.add_argument("--out", default=os.environ.get("HIDDENFORGE_KEYS_DIR",
                                                    "/var/lib/tor/hidden_service"),
                    help="key volume directory (default: $HIDDENFORGE_KEYS_DIR)")
    ap.add_argument("--threads", type=int, default=0,
                    help="worker threads (0 = auto)")
    ap.add_argument("--force", action="store_true",
                    help="archive an existing key set and generate a new address")
    ap.add_argument("--uid", type=int, default=None, help="chown output to this uid")
    ap.add_argument("--gid", type=int, default=None, help="chown output to this gid")
    ap.add_argument("--bench", action="store_true",
                    help="measure throughput and print the difficulty table only")
    ap.add_argument("--seconds", type=int, default=5,
                    help="benchmark duration in seconds (default: 5)")
    ap.add_argument("--json", action="store_true", help="machine-readable output")
    return ap


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    if not PREFIX_RE.fullmatch(args.prefix):
        return _emit(2, args.json, {"error": f"invalid prefix {args.prefix!r}: "
                                    "use base32 characters a-z and 2-7 (no 0,1,8,9), max 12"},
                     f"error: invalid prefix {args.prefix!r}")
    if not NAME_RE.fullmatch(args.name):
        return _emit(2, args.json, {"error": f"invalid name {args.name!r}"},
                     f"error: invalid name {args.name!r}")

    threads = args.threads if args.threads > 0 else (os.cpu_count() or 1)
    threads = max(1, min(threads, 256))

    try:
        rate = benchmark(args.seconds, threads)
    except Exception as exc:
        return _emit(2, args.json, {"error": f"benchmark failed: {exc}"},
                     f"error: benchmark failed: {exc}")

    table = difficulty_table(rate)

    if args.bench:
        payload = {
            "prefix": args.prefix,
            "threads": threads,
            "seconds": args.seconds,
            "keys_per_sec": round(rate, 2),
            "keys_per_sec_per_thread": round(rate / threads, 2),
            "difficulty": table,
        }
        if args.json:
            return _emit(0, True, payload, "")
        out = [f"mkp224o throughput: {rate:,.0f} keys/sec ({threads} threads, "
               f"{rate / threads:,.0f} keys/sec/thread)", "",
               "prefix len   average attempts        expected time"]
        out.extend(
            f"{row['prefix_len']:>9}   {row['average_attempts']:>18,}   "
            f"{row['estimated_human']:>13}"
            for row in table)
        return _emit(0, False, payload, "\n".join(out))

    # Honest warning for prefixes that are effectively impossible here.
    want = 32 ** len(args.prefix)
    est = want / rate if rate > 0 else float("inf")
    if est > 86400 and not args.json:
        print(f"warning: a {len(args.prefix)}-character prefix needs ~{human_duration(est)} "
              f"on this machine. Consider a shorter prefix or a faster host "
              f"(see docs/INTEGRATION.md, 'Long prefixes').", file=sys.stderr)

    try:
        result = generate(args.prefix, args.name, Path(args.out), threads,
                          args.force, args.uid, args.gid)
    except KeyRaceError as exc:
        # Must precede the FileExistsError arm: KeyRaceError is a subclass, and
        # the shared exit-code contract (manifest.json, `hiddenforge info`) gives
        # a lost race its own code. Before this, a race exited 2 -- "usage,
        # validation, or environment error" -- which tells an automated caller to
        # fix its arguments when the correct response is to retry or investigate
        # what else is writing to the key volume.
        return _emit(3, args.json, {"error": str(exc), "name": args.name},
                     f"error: {exc}")
    except FileExistsError as exc:
        return _emit(2, args.json, {"error": str(exc), "name": args.name},
                     f"error: {exc}")
    except Exception as exc:
        return _emit(1, args.json, {"error": str(exc), "name": args.name},
                     f"error: {exc}")

    result["address_matches_prefix"] = result["onion"].startswith(args.prefix)
    human = (f"Found {result['onion']}\n"
             f"Wrote {result['key_path']} (secret, mode 0600)\n"
             f"Back up {result['key_dir']} - losing it loses the address permanently.")
    return _emit(0, args.json, result, human)


if __name__ == "__main__":
    sys.exit(main())
